export function detectColor(text) {
  if (!text) return '';
  for (const [color, patterns] of Object.entries(COLOR_PATTERNS)) {
    for (const pattern of patterns) {
      if (pattern.test(text)) {
        return color;
      }
    }
  }
  return '';
}
